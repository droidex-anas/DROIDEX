// The desktop API the renderer sees as `window.droidControl`, written once
// over two transports: the preload's IPC and a paired Remote browser.
function createDesktopApi({ invoke, on }) {
  return {
    bridgeInfo: () => invoke('bridge-info'),
    sidecarStatus: () => invoke('sidecar-status'),
    onSidecarStatus: (handler) => on('sidecar-status', handler),
    pickDirectory: () => invoke('pick-directory'),
    pickFiles: () => invoke('pick-files'),
    listDirectories: (path) => invoke('list-directories', { path }),
    saveImage: (dataUrl) => invoke('save-image', { dataUrl }),
    saveAttachment: (name, dataUrl) => invoke('save-attachment', { name, dataUrl }),
    discardImage: (path) => invoke('discard-image', { path }),
    saveImageAs: (url, name) => invoke('save-image-as', { url, name }),
    notify: (title, body, options) =>
      invoke('notify', {
        title,
        body,
        silent: options?.silent === true,
        appSessionId: typeof options?.appSessionId === 'string' ? options.appSessionId : undefined,
      }),
    onNotificationActivate: (handler) => on('notification-activate', handler),
    takePendingNotificationSession: () => invoke('notification-take-pending'),
    ackNotificationActivate: (appSessionId) =>
      invoke('notification-activate-ack', { appSessionId }),
    getApiKey: () => invoke('get-api-key'),
    setApiKey: (key) => invoke('set-api-key', { key }),
    listFiles: (dir) => invoke('list-files', { dir }),
    getPerformanceMetrics: () => invoke('get-performance-metrics'),
    systemIdleTime: () => invoke('system-idle-time'),
    powerTier: () => invoke('power-tier'),
    onPowerTier: (handler) => on('power-tier', handler),
    onMemoryPressure: (handler) => on('memory-pressure', handler),
    readFile: (path) => invoke('read-file', { path }),
    readLocalImage: (url) => invoke('local-image-read', { url }),
    readRendererStorage: (keys) => invoke('renderer-storage-read', { keys }),
    writeSharedStorage: (key, value) => invoke('shared-storage-write', { key, value }),
    onSharedStorage: (handler) => on('shared-storage-changed', handler),
    repoStatus: (dir) => invoke('repo-status', { dir }),
    listEditors: () => invoke('list-editors'),
    editorIcon: (editor) => invoke('editor-icon', { editor }),
    openProject: (dir, editor, target) => invoke('open-project', { dir, editor, target }),

    gitEnvironment: (dir) => invoke('git-environment', { dir }),
    gitBranches: (dir) => invoke('git-branches', { dir }),
    gitWorktrees: (dir) => invoke('git-worktrees', { dir }),
    gitDiffStat: (dir, options) => invoke('git-diff-stat', { dir, options }),
    gitDiffFiles: (dir, options) => invoke('git-diff-files', { dir, options }),
    gitFileDiff: (dir, options) => invoke('git-file-diff', { dir, options }),
    gitMarkTurnStart: (dir, ownerId) => invoke('git-mark-turn-start', { dir, ownerId }),
    gitAdoptTurnBaseline: (dir, clientRef, appSessionId) =>
      invoke('git-adopt-turn-baseline', { dir, clientRef, appSessionId }),
    gitCreateBranch: (dir, options) => invoke('git-create-branch', { dir, options }),
    gitCheckout: (dir, options) => invoke('git-checkout', { dir, options }),
    gitCreateWorktree: (dir, options) => invoke('git-create-worktree', { dir, options }),
    gitRemoveWorktree: (dir, options) => invoke('git-remove-worktree', { dir, options }),
    gitCommit: (dir, options) => invoke('git-commit', { dir, options }),
    gitPush: (dir, options) => invoke('git-push', { dir, options }),
    gitFetch: (dir) => invoke('git-fetch', { dir }),

    githubAvailable: () => invoke('github-available'),
    githubInstall: () => invoke('github-install'),
    githubAuthenticate: () => invoke('github-authenticate'),
    githubCancelSetup: () => invoke('github-cancel-setup'),
    onGithubAuthCode: (handler) => on('github-auth-code', handler),
    githubDetectPr: (dir, options) => invoke('github-detect-pr', { dir, options }),
    githubListPrs: (dir, options) => invoke('github-list-prs', { dir, options }),
    githubViewPr: (dir, options) => invoke('github-view-pr', { dir, options }),
    githubPrDiff: (dir, options) => invoke('github-pr-diff', { dir, options }),
    githubPrChecks: (dir, options) => invoke('github-pr-checks', { dir, options }),
    githubPrComments: (dir, options) => invoke('github-pr-comments', { dir, options }),
    githubCreatePr: (dir, options) => invoke('github-create-pr', { dir, options }),
    githubPostComment: (dir, options) => invoke('github-post-comment', { dir, options }),
    githubMergePr: (dir, options) => invoke('github-merge-pr', { dir, options }),

    getOnboarding: () => invoke('onboarding-get'),
    setOnboarding: (patch) => invoke('onboarding-set', { patch }),
    appVersion: () => invoke('app-version'),
    checkAppUpdate: (options) => invoke('app-check-update', options),
    downloadAppUpdate: () => invoke('app-download-update'),
    submitFeedbackReport: (report) => invoke('feedback-report', report),
    getAutomaticDiagnostics: () => invoke('diagnostics-preference-get'),
    setAutomaticDiagnostics: (enabled) => invoke('diagnostics-preference-set', { enabled }),
    getRemoteState: () => invoke('remote-state'),
    configureRemote: (patch) => invoke('remote-configure', patch),
    setupRemoteAuthenticator: () => invoke('remote-setup'),
    confirmRemoteAuthenticator: (code) => invoke('remote-confirm', code),
    decideRemoteRequest: (id, approved) => invoke('remote-decide', { id, approved }),
    revokeRemoteDevice: (id) => invoke('remote-revoke', id),
    resetRemotePairing: () => invoke('remote-reset'),
    getPublishedProfile: () => invoke('profile-public-get'),
    publishPublicProfile: (payload) => invoke('profile-public-publish', payload),
    revokePublicProfile: (payload) => invoke('profile-public-revoke', payload),
    remoteQr: (text) => invoke('remote-qr', text),
    onRemoteState: (handler) => on('remote-state-changed', handler),
    getProfileUsage: () => invoke('profile-usage-get'),
    usageAnalyticsBootstrap: () => invoke('usage-analytics-bootstrap'),
    usageAnalyticsFirstLaunchReported: () => invoke('usage-analytics-first-launch-reported'),
    getUsageAnalytics: () => invoke('usage-analytics-preference-get'),
    setUsageAnalytics: (enabled) => invoke('usage-analytics-preference-set', { enabled }),
    getHardwareAcceleration: () => invoke('hardware-acceleration-preference-get'),
    setHardwareAcceleration: (enabled) =>
      invoke('hardware-acceleration-preference-set', { enabled }),
    relaunchApp: () => invoke('app-relaunch'),
    setAppIcon: (mode) => invoke('app-set-icon', { mode }),
    openExternal: (url) => invoke('open-external', { url }),

    terminalCreate: (options) => invoke('terminal-create', options),
    terminalResize: (id, cols, rows) => invoke('terminal-resize', { id, cols, rows }),
    terminalKill: (id) => invoke('terminal-kill', { id }),
    terminalHasChildren: (id) => invoke('terminal-has-children', { id }),
    terminalList: (appSessionId) => invoke('terminal-list', { appSessionId }),
    terminalUnsubscribe: (id) => invoke('terminal-unsubscribe', { id }),
    filesAuthorizeRoot: (root) => invoke('files-authorize-root', { root }),
    filesList: (accessToken, relative) => invoke('files-list', { accessToken, relative }),
    filesPreview: (accessToken, relative) => invoke('files-preview', { accessToken, relative }),
    filesOpen: (accessToken, relative) => invoke('files-open', { accessToken, relative }),
    filesReveal: (accessToken, relative) => invoke('files-reveal', { accessToken, relative }),

    nativeBrowserReserve: (browserSessionId, savedUrl, savedMode) =>
      invoke('native-browser-reserve', { browserSessionId, savedUrl, savedMode }),
    nativeBrowserRelease: (browserSessionId) =>
      invoke('native-browser-release', { browserSessionId }),
    nativeBrowserWorkingSessions: () => invoke('native-browser-working-sessions'),
    nativeBrowserShown: (browserSessionId, shown) =>
      invoke('native-browser-shown', { browserSessionId, shown }),
    nativeBrowserWatch: (browserSessionId, watching) =>
      invoke('native-browser-watch', { browserSessionId, watching }),
    nativeBrowserGoBack: (browserSessionId) =>
      invoke('native-browser-go-back', { browserSessionId }),
    nativeBrowserGoForward: (browserSessionId) =>
      invoke('native-browser-go-forward', { browserSessionId }),
    nativeBrowserSetDesignState: (browserSessionId, state) =>
      invoke('native-browser-set-design-state', { browserSessionId, state }),
    nativeBrowserSetShortcuts: (chords) => invoke('native-browser-set-shortcuts', { chords }),

    onNativeBrowserDesignEvent: (handler) => on('native-browser-design-event', handler),
    onNativeBrowserLoaded: (handler) => on('native-browser-loaded', handler),
    onNativeBrowserLoadFailed: (handler) => on('native-browser-load-failed', handler),
    onNativeBrowserWorking: (handler) => on('native-browser-working', handler),
    onNativeBrowserAgentPoint: (handler) => on('native-browser-agent-point', handler),
    onNativeBrowserFrame: (handler) => on('native-browser-frame', handler),
    onNativeBrowserClosed: (handler) => on('native-browser-closed', handler),
    onNativeBrowserShortcut: (handler) => on('native-browser-shortcut', handler),
  };
}

module.exports = { createDesktopApi };
