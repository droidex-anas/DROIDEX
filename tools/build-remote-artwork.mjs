import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'electron/mobile/RemoteArtwork');
const read = (name) => readFile(resolve(directory, name), 'utf8');
const [svg, css, script, template] = await Promise.all([
  read('banner.svg'), read('player.css'), read('player.js'),
  readFile(resolve(root, 'tools/remote-artwork-guide.svg'), 'utf8'),
]);
const defs = svg.match(/<defs>[\s\S]*?<\/defs>/)?.[0];
if (!defs) throw new Error('The banner must contain the shared device definitions.');
const scriptHash = createHash('sha256').update(script).digest('base64');
const chapters = [
  ['Open Remote on your computer', 'Choose the project you want to share.'],
  ['Scan or paste the pairing code', 'Scan a QR when offered, or use the copy and paste buttons.'],
  ['Approve on your computer', 'Confirm the phone you are pairing.'],
  ['Continue from your phone', 'Choose a model. Follow the work. Review the changes.'],
];
const captions = chapters.map(([title, description], index) =>
  `    <div class="caption motion chapter chapter-${index}" aria-hidden="true"><strong>${title}</strong><span>${description}</span></div>`,
).join('\n');
const buttons = chapters.map(([title], index) =>
  `    <button type="button" data-step="${index}" aria-label="Step ${index + 1}: ${title}" aria-pressed="false"></button>`,
).join('\n');
const html = `<!doctype html>
<!-- Generated by node tools/build-remote-artwork.mjs. Edit banner.svg and player.* instead. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${scriptHash}'; style-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; base-uri 'none'; form-action 'none'">
  <title>DROIDEX Remote · Pairing walkthrough</title>
  <style>${css}</style>
</head>
<body>
<main class="walkthrough" aria-label="Illustrated pairing guide, not live connection status">
  <span class="eyebrow">PAIRING GUIDE</span>
  <div class="scene" aria-hidden="true">${svg.replace('viewBox="0 0 640 236"', 'viewBox="96 0 480 236"')}</div>
  <div class="captions">
${captions}
  </div>
  <footer class="bar"><nav class="steps" aria-label="Walkthrough chapters">
${buttons}
  </nav><div class="controls"><button type="button" data-play>Pause</button><button type="button" data-replay aria-label="Replay walkthrough">Replay</button></div></footer>
  <p class="visually-hidden">${chapters.map(([title, description], index) => `${index + 1}. ${title}. ${description}`).join(' ')}</p>
  <div class="visually-hidden" data-announcement role="status"></div>
</main>
<script>${script}</script>
</body>
</html>
`;
const outputs = new Map([
  ['banner.html', html],
  ['guide.svg', template.replace('<!-- DEVICE_DEFS -->', defs)],
]);
for (const [name, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await read(name) !== content) throw new Error(`${name} is stale. Run node tools/build-remote-artwork.mjs.`);
  } else {
    await writeFile(resolve(directory, name), content);
  }
}
console.log(process.argv.includes('--check') ? 'Remote artwork is current.' : 'Built banner.html and guide.svg.');
